-- KAN-35: durable notification delivery per recipient connection. One significant event
-- (a shift queue event of KAN-25 or the future personal P4 assignment of KAN-34) becomes at
-- most one notification per recipient: (event_key, recipient_user_id) deduplicates a replayed
-- event, and the caller's eventKey must stay stable for that event.

-- One notification shown to one recipient. read_in_app_at is the recipient's own confirmation
-- in the dashboard app and is completely separate from the channel read receipt of a delivery.
CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key VARCHAR(160) NOT NULL,
    incident_id VARCHAR(128),
    priority_level_id INTEGER REFERENCES priority_levels(id),
    recipient_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    read_in_app_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_notification_event_recipient UNIQUE (event_key, recipient_user_id),
    CONSTRAINT ck_notification_title CHECK (btrim(title) <> '')
);

COMMENT ON TABLE notification IS
    'KAN-35: one notification per recipient per significant event, keyed by the stable eventKey of the caller.';
COMMENT ON COLUMN notification.read_in_app_at IS
    'The recipient confirmed reading in the dashboard app; independent of any channel read receipt.';

CREATE INDEX notification_recipient_idx ON notification (recipient_user_id, id DESC);

-- One delivery row per allowed connection of the recipient. The channel code is denormalized
-- so the row stays readable after the connection is deactivated or changed. state is the
-- furthest known signal, ordered unknown < sent < delivered < read_in_app < read_in_channel;
-- failed is the retryable outcome of an attempt and never counts as a delivered message.
-- A failed delivery is the only state a retry may resend.
CREATE TABLE notification_delivery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL REFERENCES notification(id) ON DELETE CASCADE,
    connection_id BIGINT NOT NULL REFERENCES notification_connections(id),
    channel VARCHAR(40) NOT NULL,
    state VARCHAR(32) NOT NULL,
    failure_reason VARCHAR(200),
    attempts INTEGER NOT NULL DEFAULT 0,
    sent_at TIMESTAMP(6) WITH TIME ZONE,
    delivered_at TIMESTAMP(6) WITH TIME ZONE,
    read_in_channel_at TIMESTAMP(6) WITH TIME ZONE,
    read_in_app_at TIMESTAMP(6) WITH TIME ZONE,
    last_attempt_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_notification_delivery_connection UNIQUE (notification_id, connection_id),
    CONSTRAINT ck_notification_delivery_state CHECK (
        state IN ('unknown', 'sent', 'failed', 'delivered', 'read_in_app', 'read_in_channel')
    ),
    CONSTRAINT ck_notification_delivery_attempts CHECK (attempts >= 0)
);

COMMENT ON TABLE notification_delivery IS
    'KAN-35: one delivery per allowed connection; only a failed delivery may be retried, a retry never duplicates a successful delivery.';
COMMENT ON COLUMN notification_delivery.state IS
    'Furthest known signal: unknown, sent, delivered, read_in_app, read_in_channel; failed marks a retryable attempt error.';
COMMENT ON COLUMN notification_delivery.failure_reason IS
    'Short sanitized reason code of the last failed attempt; never contains addresses, tokens or URLs.';

CREATE INDEX notification_delivery_notification_idx ON notification_delivery (notification_id);
CREATE INDEX notification_delivery_state_idx ON notification_delivery (state);
