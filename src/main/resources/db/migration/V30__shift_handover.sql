CREATE TABLE shift_handover (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id bigint NOT NULL REFERENCES users(id),
    recipient_id bigint NOT NULL REFERENCES users(id),
    request_id uuid NOT NULL,
    summary varchar(2000) NOT NULL,
    created_at timestamptz NOT NULL,
    UNIQUE (sender_id, request_id),
    CHECK (sender_id <> recipient_id)
);

CREATE INDEX shift_handover_recipient ON shift_handover(recipient_id, id);

CREATE TABLE shift_handover_item (
    handover_id bigint NOT NULL REFERENCES shift_handover(id) ON DELETE CASCADE,
    task_id bigint NOT NULL REFERENCES coordination_tasks(id) ON DELETE CASCADE,
    situation_key varchar(160) NOT NULL,
    task_updated_at timestamptz NOT NULL,
    claimed_at timestamptz,
    revoked_at timestamptz,
    CHECK (claimed_at IS NULL OR revoked_at IS NULL),
    PRIMARY KEY (handover_id, task_id)
);

CREATE UNIQUE INDEX shift_handover_pending_task
    ON shift_handover_item(task_id) WHERE claimed_at IS NULL AND revoked_at IS NULL;
