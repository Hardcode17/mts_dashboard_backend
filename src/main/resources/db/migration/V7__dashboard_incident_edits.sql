ALTER TABLE itsm_incident_change DROP CONSTRAINT itsm_incident_change_pkey,
    ADD PRIMARY KEY (source_id, incident_id, change_revision),
    ADD COLUMN coordinator_id bigint REFERENCES users(id);

CREATE TABLE coordination_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id varchar(128) NOT NULL REFERENCES itsm_incident(id),
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','completed','cancelled')),
    finished_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((status = 'open') = (finished_at IS NULL))
);
CREATE INDEX coordination_tasks_open_incident ON coordination_tasks(incident_id) WHERE status = 'open';

