CREATE TABLE incident_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_incident_id varchar(128) NOT NULL REFERENCES itsm_incident(id),
    target_incident_id varchar(128) NOT NULL REFERENCES itsm_incident(id),
    kind varchar(20) NOT NULL CHECK (kind IN ('related_to', 'causes', 'duplicate_of')),
    confirmed_by_user_id bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_incident_link UNIQUE (source_incident_id, target_incident_id, kind),
    CONSTRAINT chk_link_not_self CHECK (source_incident_id <> target_incident_id),
    CONSTRAINT chk_related_link_order CHECK (
        kind <> 'related_to' OR source_incident_id COLLATE "C" < target_incident_id COLLATE "C"
    )
);

CREATE INDEX ix_incident_links_target ON incident_links (target_incident_id);
