CREATE TABLE coordination_task_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coordination_task_id bigint NOT NULL REFERENCES coordination_tasks(id) ON DELETE CASCADE,
    coordinator_group_id bigint NOT NULL REFERENCES coordinator_groups(id),
    assigned_by_user_id bigint NOT NULL REFERENCES users(id),
    assigned_at timestamptz NOT NULL,
    ended_at timestamptz,
    status varchar(16) NOT NULL,
    redirected_by_user_id bigint REFERENCES users(id),
    redirect_reason varchar(1000),
    CHECK ((status = 'assigned' AND ended_at IS NULL)
        OR (status IN ('redirected', 'completed') AND ended_at IS NOT NULL)),
    CHECK (ended_at IS NULL OR ended_at >= assigned_at),
    CHECK ((status = 'redirected') = (redirected_by_user_id IS NOT NULL AND redirect_reason IS NOT NULL))
);

CREATE UNIQUE INDEX coordination_task_assignments_one_active
    ON coordination_task_assignments(coordination_task_id) WHERE ended_at IS NULL;
CREATE INDEX coordination_task_assignments_history
    ON coordination_task_assignments(coordination_task_id, id);
