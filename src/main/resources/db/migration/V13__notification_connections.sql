CREATE TABLE priority_levels (
    id integer PRIMARY KEY CHECK (id BETWEEN 1 AND 4),
    code varchar(32) NOT NULL UNIQUE,
    name varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO priority_levels (id, code, name) VALUES
    (1, 'low', 'P1'), (2, 'medium', 'P2'), (3, 'high', 'P3'), (4, 'highest', 'P4');

CREATE TABLE notification_connections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    notification_type_id bigint NOT NULL REFERENCES notification_types(id),
    connection_metadata jsonb NOT NULL DEFAULT '{}',
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (jsonb_typeof(connection_metadata) = 'object')
);

CREATE INDEX notification_connections_user_active_idx ON notification_connections (user_id, is_active);
CREATE INDEX notification_connections_type_idx ON notification_connections (notification_type_id);

CREATE TABLE notification_connection_priorities (
    notification_connection_id bigint NOT NULL REFERENCES notification_connections(id) ON DELETE CASCADE,
    priority_level_id integer NOT NULL REFERENCES priority_levels(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (notification_connection_id, priority_level_id)
);
