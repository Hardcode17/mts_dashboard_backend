CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_issuer varchar(512) NOT NULL,
    identity_subject varchar(255) NOT NULL,
    login varchar(120) NOT NULL,
    display_name varchar(255) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_identity_unique UNIQUE (identity_issuer, identity_subject),
    CONSTRAINT users_identity_not_blank CHECK (btrim(identity_issuer) <> '' AND btrim(identity_subject) <> '')
);
