CREATE TABLE coordinator_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    description text,
    source_team_id bigint REFERENCES itsm_external_group (id),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX coordinator_groups_source_team_idx ON coordinator_groups (source_team_id);

CREATE TABLE coordinator_group_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coordinator_group_id bigint NOT NULL REFERENCES coordinator_groups (id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (coordinator_group_id, user_id)
);

CREATE INDEX coordinator_group_members_user_idx ON coordinator_group_members (user_id, is_active);

CREATE TABLE coordinator_availability (
    user_id bigint PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    available boolean NOT NULL,
    available_since timestamptz,
    generation bigint NOT NULL DEFAULT 0 CHECK (generation >= 0),
    CHECK ((generation > 0) = (available_since IS NOT NULL)),
    CHECK (NOT available OR generation > 0)
);
